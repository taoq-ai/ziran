"""Rego policy renderer — generates Open Policy Agent modules."""

from __future__ import annotations

import json
from typing import TYPE_CHECKING

from ziran.domain.entities.policy import GuardrailPolicy, GuardrailPolicyFormat
from ziran.domain.ports.policy_renderer import PolicyRenderer
from ziran.domain.text import printable

if TYPE_CHECKING:
    from ziran.domain.entities.capability import DangerousChain


def _rego_str(value: str) -> str:
    """*value* as a Rego (JSON) string: printable characters raw, the rest JSON-escaped."""
    body = "".join(c if c.isprintable() and c not in '"\\' else json.dumps(c)[1:-1] for c in value)
    return f'"{body}"'


class RegoRenderer(PolicyRenderer):
    """Render DangerousChain findings as Rego deny rules in OPA 1.0 syntax.

    ``import rego.v1`` keeps the module loadable in OPA 0.x from 0.59. Values go in as JSON
    string literals, which Rego strings share.
    """

    @property
    def format(self) -> GuardrailPolicyFormat:
        return GuardrailPolicyFormat.REGO

    def render(
        self,
        finding: DangerousChain,
        finding_id: str,
    ) -> GuardrailPolicy:
        tools = finding.tools
        chain_label = " \u2192 ".join(tools)
        vuln = finding.vulnerability_type

        lines: list[str] = [
            "# Generated by Ziran",
            f"# Finding: {printable(finding_id)}",
            f"# Chain: {printable(chain_label)}",
            f"# Severity: {printable(finding.risk_level)}",
            "package ziran.guardrails",
            "",
            "import rego.v1",
            "",
            "deny contains msg if {",
            "    some i",
        ]

        # Add tool-match clauses for each consecutive pair
        for idx, tool in enumerate(tools):
            offset = f"i + {idx}" if idx > 0 else "i"
            lines.append(
                f"    input.trace[{offset}].tool == {_rego_str(tool)}",
            )

        msg_text = f"Ziran finding {finding_id}: {chain_label} ({vuln})"
        lines.append(f"    msg := {_rego_str(msg_text)}")
        lines.append("}")

        content = "\n".join(lines) + "\n"

        return GuardrailPolicy(
            finding_id=finding_id,
            format=GuardrailPolicyFormat.REGO,
            content=content,
            tool_chain=list(tools),
            severity=finding.risk_level,
        )
