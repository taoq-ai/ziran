"""Sigma renderer: detection rules over OpenTelemetry GenAI tool spans (spec 120).

A chain becomes one single-event rule per tool (an ``execute_tool`` span naming it) and, for two
or more tools, a ``temporal`` correlation rule per session. Only a chain one recorded attack ran
is rendered, and each file passes a self-check before it is returned.
"""

from __future__ import annotations

import re
import uuid
from typing import TYPE_CHECKING, Any

import yaml

from ziran.domain.entities.ci import chain_fingerprint
from ziran.domain.entities.policy import GuardrailPolicy, GuardrailPolicyFormat
from ziran.domain.ports.policy_renderer import PolicyRenderer
from ziran.domain.sigma import TAG, event_matches, sigma_matches, sigma_schema_errors
from ziran.domain.text import printable

if TYPE_CHECKING:
    from collections.abc import Mapping, Sequence

    from ziran.domain.entities.capability import DangerousChain
    from ziran.domain.entities.phase import CampaignResult

_NAMESPACE = uuid.UUID("0f6f2f0e-5c1e-4f4b-9a39-6c2a8e0b7d11")  # fixed: rule ids stay stable
_TIMESPAN = "1h"
_SESSION = "gen_ai.conversation.id"
_TRACE_ID = re.compile(r"[0-9a-f]{32}")  # W3C trace id, as spec 117 writes it
_UNORDERED = (
    " The correlation is unordered: Sigma temporal_ordered runs only on SQLite backends, so an"
    " ordered match needs a native query (Splunk SPL, Elastic ES|QL or EQL)."
)


def _call_name(call: Any) -> str:
    """The tool name of one recorded call (``tool``, ``name`` or OpenAI's ``function.name``)."""
    if not isinstance(call, dict):
        return ""
    fn = call.get("function")
    name = call.get("tool") or call.get("name") or (fn.get("name") if isinstance(fn, dict) else "")
    return name if isinstance(name, str) else ""


def _names(tool: str) -> list[str]:
    """The span names a chain tool matches: its id and, for ``tool_<name>``, the bare name."""
    return list(dict.fromkeys([tool, tool.removeprefix("tool_") or tool]))


def _escape(value: str) -> str:
    """A Sigma string value matching *value* literally (no wildcard)."""
    return re.sub(r"([*?\\])", r"\\\1", value)


class SigmaRenderer(PolicyRenderer):
    """Render proven DangerousChain findings as Sigma rules over OTel GenAI tool spans."""

    def __init__(self, result: CampaignResult, *, exclude_probes: bool = False) -> None:
        self._result = result
        traces = {
            m.get("trace_id") if isinstance(m, dict) else m
            for ar in result.attack_results
            for m in ar.get("probe_markers") or []
        }
        self._probe_traces = sorted(map(str, traces)) if exclude_probes else []
        self._bad_trace = any(not _TRACE_ID.fullmatch(t) for t in self._probe_traces)

    @property
    def format(self) -> GuardrailPolicyFormat:
        return GuardrailPolicyFormat.SIGMA

    def render(self, finding: DangerousChain, finding_id: str) -> GuardrailPolicy:
        tools = list(dict.fromkeys(finding.tools))
        policy = GuardrailPolicy(
            finding_id=finding_id,
            format=GuardrailPolicyFormat.SIGMA,
            content="",
            tool_chain=list(finding.tools),
            severity=finding.risk_level,
        )
        if self._bad_trace:  # a tampered result: a wildcard here would hide real alerts
            return policy.model_copy(
                update={"skipped": True, "skip_reason": "a probe trace id is not 32 hex digits"}
            )
        proving = [ar for ar in self._result.attack_results if self._ran_all(ar, tools)]
        if not proving:
            return policy.model_copy(
                update={"skipped": True, "skip_reason": "no recorded attack called every tool"}
            )
        docs = self._rules(finding, finding_id, tools, proving)
        vector = str(proving[0].get("vector_id", ""))
        content = (
            f"# Generated by Ziran from finding {printable(finding_id)}\n"
            f"# Self-check: matched the recorded calls of {printable(vector)}, not the session "
            f"without {printable(tools[-1])}\n"
            + yaml.safe_dump_all(docs, sort_keys=False, explicit_start=True)
        )
        failure = self._self_check(content, docs, proving[0])
        if failure:
            return policy.model_copy(
                update={"skipped": True, "skip_reason": f"self-check failed: {failure}"}
            )
        return policy.model_copy(update={"content": content})

    @staticmethod
    def _ran_all(attack: Mapping[str, Any], tools: Sequence[str]) -> bool:
        evidence = attack.get("evidence")
        calls = evidence.get("tool_calls") if isinstance(evidence, dict) else None
        called = ({_call_name(c) for c in calls} if isinstance(calls, list) else set()) - {""}
        return all(called & set(_names(t)) for t in tools)

    def _rules(
        self,
        finding: DangerousChain,
        finding_id: str,
        tools: list[str],
        proving: list[dict[str, Any]],
    ) -> list[dict[str, Any]]:
        fingerprint = chain_fingerprint(self._result.target_agent, finding.vulnerability_type)
        vuln = printable(finding.vulnerability_type)
        references = [f"ziran finding {finding_id}", f"ziran fingerprint {fingerprint}"]
        references += [
            f"ziran vector {v}" for v in dict.fromkeys(str(a.get("vector_id")) for a in proving)
        ]
        tags = sorted(
            {f"atlas.{str(t).lower()}" for a in proving for t in a.get("atlas_mapping") or []}
            | {
                f"owasp.{str(t).lower()}"
                for a in proving
                for key in ("owasp_mapping", "owasp_agentic_mapping")
                for t in a.get(key) or []
            }
        )
        tags = [t for t in tags if TAG.fullmatch(t)]
        level = finding.risk_level  # the self-check refuses a level Sigma has no name for
        slug = re.sub(r"[^a-z0-9]+", "_", finding_id.lower()).strip("_")
        # hex: uuid5 encodes a str as strict UTF-8, which a lone surrogate in a tool name breaks
        seed = f"{fingerprint}/{'/'.join(tools)}".encode("utf-8", "surrogatepass").hex()
        common = {"status": "experimental", "references": references}

        docs: list[dict[str, Any]] = []
        for step, tool in enumerate(tools, 1):
            detection: dict[str, Any] = {
                "selection": {
                    "gen_ai.operation.name": "execute_tool",
                    "gen_ai.tool.name": [_escape(n) for n in _names(tool)],
                }
            }
            if self._probe_traces:
                detection["filter_ziran_probe"] = {
                    "trace_id": list(map(_escape, self._probe_traces))
                }
                detection["condition"] = "selection and not filter_ziran_probe"
            else:
                detection["condition"] = "selection"
            docs.append(
                {
                    "title": f"ZIRAN {vuln} step {step} of {len(tools)}: {printable(tool)}"[:256],
                    "id": str(uuid.uuid5(_NAMESPACE, f"{seed}/{step}")),
                    "name": f"{slug}_step_{step}",
                    **common,
                    "description": f"Agent tool call to {printable(tool)}, step {step} of the "
                    f"{vuln} chain {finding_id}.",
                    "logsource": {"product": "opentelemetry", "service": "gen_ai"},
                    "detection": detection,
                    "falsepositives": [f"Legitimate use of the {printable(tool)} tool"],
                    "level": level if len(tools) == 1 else "informational",
                    "tags": tags,
                }
            )
        if len(tools) > 1:
            docs.append(
                {
                    "title": f"ZIRAN {vuln}: {' then '.join(map(printable, tools))}"[:256],
                    "id": str(uuid.uuid5(_NAMESPACE, f"{seed}/correlation")),
                    "name": slug,
                    **common,
                    "description": printable(finding.exploit_description).rstrip(".")
                    + "."
                    + _UNORDERED,
                    "correlation": {
                        "type": "temporal",
                        "rules": [d["name"] for d in docs],
                        "group-by": [_SESSION],
                        "timespan": _TIMESPAN,
                    },
                    "falsepositives": ["A benign task that uses every tool of the chain"],
                    "level": level,
                    "tags": tags,
                }
            )
        return docs

    @staticmethod
    def _self_check(content: str, docs: list[dict[str, Any]], attack: Mapping[str, Any]) -> str:
        """Why the rules fail the check, or ``""``: schema, the recorded session, the benign one."""
        for doc in docs:
            errors = sigma_schema_errors(doc)
            if errors:
                return f"{doc['name']}: {'; '.join(errors)}"
        calls = (attack.get("evidence") or {}).get("tool_calls") or []
        spans = [
            {
                "time": float(i),
                "trace_id": "0" * 32,
                "gen_ai.operation.name": "execute_tool",
                "gen_ai.tool.name": _call_name(c),
                _SESSION: "ziran-self-check",
            }
            for i, c in enumerate(calls)
        ]
        if not sigma_matches(content, spans):
            return "the rule does not match the recorded calls"
        last = docs[-2] if len(docs) > 1 else docs[0]  # the chain's last tool rule
        benign = [s for s in spans if not event_matches(last, s)]
        if sigma_matches(content, benign):
            return "the rule matches the session without the chain's last tool"
        return ""
